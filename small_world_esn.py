"""Small-world echo state network (SW-ESN): memory capacity experiments.

Reimplementation of the memory-capacity task from
Kawai, Park & Asada (2019), Neural Networks 112, 15-23.
  - Fig 4: input and output nodes chosen randomly (no overlap)
  - Fig 5: input and output nodes spatially segregated
"""

import numpy as np
import networkx as nx
import scipy.sparse as sp
import matplotlib.pyplot as plt

N, E = 500, 6                 # reservoir size, edges per node
N_IN = N_OUT = 100
BETA = 1e-10                  # ridge regularization
MAX_TAU = 40                  # delays 1..40
T_STEPS = 4100
WASHOUT, TRAIN_END = 100, 2100
ALPHAS = np.round(np.arange(0.1, 2.51, 0.1), 1)
PS = [0, 0.001, 0.01, 0.1, 0.2, 0.5, 1.0]
N_TRIALS = 20
BASE_SEED = 1000


def run_trial(p, seed, segregated):
    """Return MC for every spectral radius in ALPHAS (one network, one input)."""
    # Separate random streams for weights and for the input series
    ss = np.random.SeedSequence(seed)
    rng_w, rng_u = [np.random.default_rng(s) for s in ss.spawn(2)]

    # Small-world reservoir with random weights, scaled later to radius alpha
    G = nx.watts_strogatz_graph(N, E, p, seed=seed)
    W0 = rng_w.uniform(-0.5, 0.5, (N, N)) * nx.to_numpy_array(G)
    rho0 = np.max(np.abs(np.linalg.eigvals(W0)))
    W0 = sp.csr_matrix(W0)

    # Input / output node placement
    if segregated:
        in_idx = np.arange(N_IN)                      # one side of the ring
        out_idx = np.arange(N // 2, N // 2 + N_OUT)   # opposite side
    else:
        perm = rng_w.permutation(N)
        in_idx, out_idx = perm[:N_IN], perm[N_IN:N_IN + N_OUT]

    w_in = np.zeros(N)
    w_in[in_idx] = rng_w.uniform(-0.5, 0.5, N_IN)

    # A new random input series for every trial
    u = rng_u.uniform(-1, 1, T_STEPS)

    # Targets: input delayed by tau = 1..MAX_TAU
    Y = np.zeros((T_STEPS, MAX_TAU))
    for tau in range(1, MAX_TAU + 1):
        Y[tau:, tau - 1] = u[:-tau]

    mc_per_alpha = []
    for alpha in ALPHAS:
        W = W0 * (alpha / rho0)
        x = np.zeros(N)
        S = np.empty((T_STEPS, N_OUT))
        for t in range(T_STEPS):
            x = np.tanh(W @ x + w_in * u[t])
            S[t] = x[out_idx]

        Xtr, Xte = S[WASHOUT:TRAIN_END], S[TRAIN_END:]

        # Ridge regression for all delays at once
        Wout = np.linalg.solve(
            Xtr.T @ Xtr + BETA * np.eye(N_OUT),
            Xtr.T @ Y[WASHOUT:TRAIN_END],
        )

        yp = Xte @ Wout
        yt = Y[TRAIN_END:]
        yp = yp - yp.mean(0)
        yt = yt - yt.mean(0)
        with np.errstate(invalid="ignore", divide="ignore"):
            corr2 = (yp * yt).sum(0) ** 2 / ((yp**2).sum(0) * (yt**2).sum(0))
        mc_per_alpha.append(np.nan_to_num(corr2).sum())

    return mc_per_alpha


def run_experiment(segregated):
    results = {}
    for p in PS:
        print(f"{'segregated' if segregated else 'random'} IO, p = {p}")
        results[p] = np.array(
            [run_trial(p, BASE_SEED + i, segregated) for i in range(N_TRIALS)]
        )
    return results  # shape per p: (N_TRIALS, len(ALPHAS))


def plot_results(results, name):
    # (a) MC versus spectral radius
    plt.figure(figsize=(7, 5))
    for p in PS:
        plt.plot(ALPHAS, results[p].mean(0), label=p)
    plt.xlabel("Spectral radius α")
    plt.ylabel("Memory capacity MC")
    plt.title(f"{name}: MC vs. spectral radius")
    plt.legend(title="Rewiring probability p")
    plt.tight_layout()
    plt.savefig(f"{name}_a.png", dpi=200)
    plt.show()

    # (b) MC summed over alpha, mean and std across trials
    sums = [results[p].sum(1) for p in PS]
    plt.figure(figsize=(7, 5))
    plt.bar([str(p) for p in PS], [s.mean() for s in sums],
            yerr=[s.std() for s in sums], capsize=3)
    plt.xlabel("Rewiring probability p")
    plt.ylabel("Σ MC over α")
    plt.title(f"{name}: total MC")
    plt.tight_layout()
    plt.savefig(f"{name}_b.png", dpi=200)
    plt.show()


if __name__ == "__main__":
    results_random = run_experiment(segregated=False)
    plot_results(results_random, "fig4_random_io")

    results_seg = run_experiment(segregated=True)
    plot_results(results_seg, "fig5_segregated_io")