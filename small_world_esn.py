N, E = 500, 6
N_IN = N_OUT = 100
BETA = 1e-10
MAX_TAU = 40
T_STEPS = 4100
ALPHAS = np.round(np.arange(0.1, 2.51, 0.1), 1)
PS = [0, 0.001, 0.01, 0.1, 0.2, 0.5, 1.0]
N_TRIALS = 20


def run_trial(p, seed):
    rng = np.random.default_rng(seed)

    # Create the network and assign random connection weights
    G = nx.watts_strogatz_graph(N, E, p, seed=seed)
    W0 = rng.uniform(-0.5, 0.5, (N, N)) * nx.to_numpy_array(G)
    rho0 = np.max(np.abs(np.linalg.eigvals(W0)))
    W0 = sp.csr_matrix(W0)

    # Choose input and output nodes without overlap
    perm = rng.permutation(N)
    in_idx, out_idx = perm[:N_IN], perm[N_IN:N_IN + N_OUT]

    w_in = np.zeros(N)
    w_in[in_idx] = rng.uniform(-0.5, 0.5, N_IN)

    u = rng.uniform(-1, 1, T_STEPS)

    # Build target signals for each time delay
    Y = np.zeros((T_STEPS, MAX_TAU))
    for tau in range(1, MAX_TAU + 1):
        Y[tau:, tau - 1] = u[:-tau]

    mc_per_alpha = []

    for alpha in ALPHAS:
        W = W0 * (alpha / rho0)
        x = np.zeros(N)
        S = np.empty((T_STEPS, N_OUT))

        # Run the reservoir and record the output node states
        for t in range(T_STEPS):
            x = np.tanh(W @ x + w_in * u[t])
            S[t] = x[out_idx]

        Xtr, Xte = S[100:2100], S[2100:4100]

        # Fit output weights for all delays
        Wout = np.linalg.solve(
            Xtr.T @ Xtr + BETA * np.eye(N_OUT),
            Xtr.T @ Y[100:2100]
        )

        yp = Xte @ Wout
        yt = Y[2100:4100]

        # Calculate squared correlation for each delay
        yp = yp - yp.mean(0)
        yt = yt - yt.mean(0)
        corr2 = (
            (yp * yt).sum(0) ** 2
            / ((yp**2).sum(0) * (yt**2).sum(0))
        )

        mc_per_alpha.append(np.nan_to_num(corr2).sum())

    return mc_per_alpha


