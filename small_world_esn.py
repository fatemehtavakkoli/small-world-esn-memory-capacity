# Small-World Echo State Network (SW-ESN)
# Example: Memory Capacity at a Fixed Spectral Radius
# Related to Figures 4 and 5 of the reference paper

import numpy as np
import networkx as nx
import matplotlib.pyplot as plt


class EchoStateNetwork:
    def __init__(
        self,
        reservoir_size=500,
        spectral_radius=1.2,
        rewiring_probability=0.1,
        n_input_nodes=100,
        n_output_nodes=100,
        ridge_beta=1e-10,
        seed=42,
    ):
        self.reservoir_size = reservoir_size
        self.spectral_radius = spectral_radius
        self.ridge_beta = ridge_beta

        rng = np.random.default_rng(seed)

        # Build the Watts-Strogatz network
        G = nx.watts_strogatz_graph(
            n=reservoir_size,
            k=6,
            p=rewiring_probability,
            seed=seed,
        )

        adjacency = nx.to_numpy_array(G)

        # Assign random weights to existing connections
        W0 = rng.uniform(
            -0.5, 0.5,
            size=(reservoir_size, reservoir_size)
        ) * adjacency

        # Scale the weights to the chosen spectral radius
        rho = np.max(np.abs(np.linalg.eigvals(W0)))

        self.W_res = W0 * (spectral_radius / rho)

        # Set the input nodes and their weights
        self.W_in = np.zeros((reservoir_size, 1))
        self.input_indices = np.arange(n_input_nodes)

        self.W_in[self.input_indices, 0] = rng.uniform(
            -0.5, 0.5, size=n_input_nodes
        )

        # Select output nodes from a separate region of the reservoir
        output_start = reservoir_size // 2
        self.output_indices = np.arange(
            output_start,
            output_start + n_output_nodes,
        )

        if self.output_indices[-1] >= reservoir_size:
            raise ValueError(
                "Output nodes exceed reservoir boundaries."
            )

        self.W_out = None

    def run_reservoir(self, input_data):
        input_data = np.asarray(input_data).reshape(-1, 1)

        states = np.zeros(
            (len(input_data), self.reservoir_size)
        )

        x = np.zeros(self.reservoir_size)

        for t in range(len(input_data)):
            x = np.tanh(
                self.W_res @ x
                + self.W_in[:, 0] * input_data[t, 0]
            )
            states[t] = x

        return states

    def train(self, input_data, target_data):
        states = self.run_reservoir(input_data)

        X = states[100:2100][:, self.output_indices]
        Y = np.asarray(target_data).reshape(-1, 1)[100:2100]

        # Fit the output weights using ridge regression
        identity = np.eye(X.shape[1])

        self.W_out = np.linalg.solve(
            X.T @ X + self.ridge_beta * identity,
            X.T @ Y,
        ).T

        return states

    def predict(self, input_data):
        if self.W_out is None:
            raise ValueError("Train the ESN before prediction.")

        states = self.run_reservoir(input_data)
        selected_states = states[:, self.output_indices]

        return selected_states @ self.W_out.T


