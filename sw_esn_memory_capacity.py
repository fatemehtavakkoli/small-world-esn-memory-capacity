# Fig 4: memory capacity with randomly chosen input and output nodes
import scipy.sparse as sp
N, E = 500, 6
N_IN = N_OUT = 100
BETA = 1e-10
MAX_TAU = 40
T_STEPS = 4100
ALPHAS = np.round(np.arange(0.1, 2.51, 0.1), 1)
PS = [0, 0.001, 0.01, 0.1, 0.2, 0.5, 1.0]
N_TRIALS = 20


def run_trial(p, seed):
    rng = np.random.default_rng(seed)

    # Create the network and assign random connection weights
    G = nx.watts_strogatz_graph(N, E, p, seed=seed)
    W0 = rng.uniform(-0.5, 0.5, (N, N)) * nx.to_numpy_array(G)
    rho0 = np.max(np.abs(np.linalg.eigvals(W0)))
    W0 = sp.csr_matrix(W0)

    # Choose input and output nodes without overlap
    perm = rng.permutation(N)
    in_idx, out_idx = perm[:N_IN], perm[N_IN:N_IN + N_OUT]

    w_in = np.zeros(N)
    w_in[in_idx] = rng.uniform(-0.5, 0.5, N_IN)

    u = rng.uniform(-1, 1, T_STEPS)

    # Build target signals for each time delay
    Y = np.zeros((T_STEPS, MAX_TAU))
    for tau in range(1, MAX_TAU + 1):
        Y[tau:, tau - 1] = u[:-tau]

    mc_per_alpha = []

    for alpha in ALPHAS:
        W = W0 * (alpha / rho0)
        x = np.zeros(N)
        S = np.empty((T_STEPS, N_OUT))

        # Run the reservoir and record the output node states
        for t in range(T_STEPS):
            x = np.tanh(W @ x + w_in * u[t])
            S[t] = x[out_idx]

        Xtr, Xte = S[100:2100], S[2100:4100]

        # Fit output weights for all delays
        Wout = np.linalg.solve(
            Xtr.T @ Xtr + BETA * np.eye(N_OUT),
            Xtr.T @ Y[100:2100]
        )

        yp = Xte @ Wout
        yt = Y[2100:4100]

        # Calculate squared correlation for each delay
        yp = yp - yp.mean(0)
        yt = yt - yt.mean(0)
        corr2 = (
            (yp * yt).sum(0) ** 2
            / ((yp**2).sum(0) * (yt**2).sum(0))
        )

        mc_per_alpha.append(np.nan_to_num(corr2).sum())

    return mc_per_alpha


results = {}

for p in PS:
    print("p =", p)

    # Repeat the experiment with different random seeds
    results[p] = np.array([
        run_trial(p, 1000 + i)
        for i in range(N_TRIALS)
    ])


# Figure 4a: Memory capacity across spectral radii
plt.figure(figsize=(7, 5))

for p in PS:
    plt.plot(ALPHAS, results[p].mean(0), label=p)

plt.xlabel("Spectral radius α")
plt.ylabel("Memory capacity MC")
plt.legend(title="Rewiring probability p")
plt.show()


# Figure 4b: Total memory capacity for each rewiring probability
sums = [results[p].sum(1) for p in PS]

plt.figure(figsize=(7, 5))
plt.bar(
    [str(p) for p in PS],
    [s.mean() for s in sums],
    yerr=[s.std() for s in sums],
    capsize=3
)

plt.xlabel("Rewiring probability p")
plt.ylabel("Σ MC over α")
plt.show()

# Fig 5: Memory capacity with segregated input and output nodes

N, E = 500, 6
N_IN = N_OUT = 100
BETA = 1e-10
MAX_TAU = 40
T_STEPS = 4100
ALPHAS = np.round(np.arange(0.1, 2.51, 0.1), 1)
PS = [0, 0.001, 0.01, 0.1, 0.2, 0.5, 1.0]
N_TRIALS = 20

IN_IDX = np.arange(0, 100)
OUT_IDX = np.arange(250, 350)


def run_trial(p, seed):
    ss = np.random.SeedSequence(seed)
    rng_w, rng_u = [np.random.default_rng(s) for s in ss.spawn(2)]

    # Build the network and assign random weights
    G = nx.watts_strogatz_graph(N, E, p, seed=seed)
    W0 = rng_w.uniform(-0.5, 0.5, (N, N)) * nx.to_numpy_array(G)
    rho0 = np.max(np.abs(np.linalg.eigvals(W0)))
    W0 = sp.csr_matrix(W0)

    # Input weights for the selected nodes
    w_in = np.zeros(N)
    w_in[IN_IDX] = rng_w.uniform(-0.5, 0.5, N_IN)

    u = rng_u.uniform(-1, 1, T_STEPS)

    # Create the delayed target signals
    Y = np.zeros((T_STEPS, MAX_TAU))
    for tau in range(1, MAX_TAU + 1):
        Y[tau:, tau - 1] = u[:-tau]

    mc_list = []

    for alpha in ALPHAS:
        W = W0 * (alpha / rho0)
        x = np.zeros(N)
        S = np.empty((T_STEPS, N_OUT))

        # Run the reservoir
        for t in range(T_STEPS):
            x = np.tanh(W @ x + w_in * u[t])
            S[t] = x[OUT_IDX]

        X_train, X_test = S[100:2100], S[2100:4100]

        # Train the readout
        W_out = np.linalg.solve(
            X_train.T @ X_train + BETA * np.eye(N_OUT),
            X_train.T @ Y[100:2100],
        )

        y_pred = X_test @ W_out - (X_test @ W_out).mean(0)
        y_true = Y[2100:4100] - Y[2100:4100].mean(0)

        # Calculate memory capacity
        with np.errstate(invalid="ignore", divide="ignore"):
            corr2 = (y_pred * y_true).sum(0) ** 2 / (
                (y_pred ** 2).sum(0) * (y_true ** 2).sum(0)
            )

        mc_list.append(np.nan_to_num(corr2).sum())

    return mc_list


results = {}

# Repeat the experiment for each rewiring probability
for p in PS:
    print("p =", p)
    results[p] = np.array([
        run_trial(p, 1000 + i) for i in range(N_TRIALS)
    ])


# Figure 5a: Memory capacity vs. spectral radius
plt.figure(figsize=(7, 5))

for p in PS:
    plt.plot(ALPHAS, results[p].mean(0), label=p)

plt.xlabel("Spectral radius α")
